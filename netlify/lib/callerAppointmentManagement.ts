import { createHmac, timingSafeEqual } from 'node:crypto'
import type { SupabaseClient } from '@supabase/supabase-js'
import { objectValue, textValue, uuid, validDate, validTime } from './appointmentScheduling'
import { normalizeE164 } from './retell'

export const spokenBookingReference = (id: string) => id.replaceAll('-', '').slice(0, 12)

const bookingReference = (value: unknown) => {
  if (uuid(value)) return value.toLowerCase()
  const compact = typeof value === 'string' ? value.toLowerCase().replace(/[\s-]/g, '') : ''
  return /^[0-9a-f]{12}$/.test(compact) ? compact : null
}

const heardCancellationConfirmation = (call: Record<string, unknown>) => {
  // Tool arguments are generated by the agent. Require the actual caller's reply
  // in the signed call transcript as well as the tool's confirmed flag.
  const turns = Array.isArray(call.transcript_object) && call.transcript_object.length
    ? call.transcript_object.map(objectValue)
    : typeof call.transcript === 'string'
      ? Array.from(call.transcript.matchAll(/^\s*(Agent|User):[ \t]*([^\r\n]*)/gim),
        ([, role, content]) => ({ role: role.toLowerCase(), content }))
      : []
  const dialogue = turns.filter(turn => turn.role === 'agent' || turn.role === 'user')
  const reply = dialogue.at(-1)
  const question = dialogue.at(-2)
  return reply?.role === 'user' && question?.role === 'agent' &&
    typeof question.content === 'string' && /say [“"'‘]?yes,? cancel/i.test(question.content) &&
    typeof reply.content === 'string' &&
    /^(?:yes[\s,]+(?:please[\s,]+)?cancel(?:[\s,]+(?:it|that|the appointment|please))?|confirm cancellation)[.! ]*$/i.test(reply.content.trim())
}

export const CALLER_APPOINTMENT_TOOLS = ['find_appointment','reschedule_appointment','cancel_appointment','check_appointment_availability'] as const
type CallerTool = typeof CALLER_APPOINTMENT_TOOLS[number]
export const isCallerAppointmentTool = (name: unknown): name is CallerTool =>
  CALLER_APPOINTMENT_TOOLS.some(tool => tool === name)

type Context = { clientId: string; agentId: string; callId: string; phone: string; key: string }
const TTL = 15 * 60_000
const failed = (reason = 'verification_failed') => ({
  success: false, reason,
  instruction: 'Do not disclose any booking details or claim a change. If verification fails, direct the caller to the business.',
})
const mac = (context: Context, id: string, version: number, expires: number) =>
  createHmac('sha256',context.key).update(JSON.stringify([
    'recepta-caller-appointment-v1',context.clientId,context.agentId,context.callId,context.phone,id,version,expires,
  ])).digest('base64url')
export const appointmentSession = (context: Context, id: string, version: number, now = Date.now()) => {
  const expires = now+TTL
  return version+'.'+expires+'.'+mac(context,id,version,expires)
}
export const verifyAppointmentSession = (context: Context, id: string, token: unknown, now = Date.now()) => {
  if (typeof token !== 'string' || !/^\d{1,10}\.\d{13}\.[A-Za-z0-9_-]{43}$/.test(token)) return null
  const [v, exp, signature] = token.split('.')
  const version = Number(v), expires = Number(exp)
  if (!Number.isInteger(version) || version<0 || expires<=now || expires>now+TTL) return null
  const expected = Buffer.from(mac(context,id,version,expires))
  const actual = Buffer.from(signature)
  return actual.length===expected.length && timingSafeEqual(actual,expected) ? version : null
}

export const manageCallerAppointment = async (
  db: SupabaseClient, tool: CallerTool, call: Record<string,unknown>, args: Record<string,unknown>,
  identity: Omit<Context,'phone'>,
) => {
  // Do not accept a phone number, tenant ID or call ID from tool arguments.
  // The endpoint has already verified the raw signed Retell wrapper. SQL also
  // requires an active, unexpired inbound minute reservation for this exact call.
  const phone = normalizeE164(textValue(call.from_number,60))
  if (!phone || call.call_type !== 'phone_call' || call.direction !== 'inbound') return failed()
  const context = { ...identity, phone }
  const invoke = async (id: string, action: string, version: number|null = null, checkTime?: string) => {
    const {data,error} = await db.rpc('recepta_caller_appointment',{
      p_client:context.clientId,p_agent:context.agentId,p_call:context.callId,p_phone:phone,p_reference:id,
      p_action:action,p_version:version,
      p_date:action==='reschedule' ? args.new_date : action==='check' ? args.requested_date : null,
      p_time:action==='reschedule' ? args.new_time : action==='check' ? (checkTime ?? args.requested_time) : null,
      p_confirmed:action==='cancel' && args.confirmed===true,
    })
    if (error) throw error
    return objectValue(data)
  }
  const verified = (record: Record<string,unknown>) => {
    if (!uuid(record.appointment_id) || !Number.isInteger(record.booking_version)) throw new Error('Invalid caller appointment response.')
    const id = record.appointment_id.toLowerCase()
    return {
      appointment_id:id,status:record.status,start:record.start,time_zone:record.time_zone,
      duration_minutes:record.duration_minutes,
      verified_session_token:appointmentSession(context,id,Number(record.booking_version)),
    }
  }
  if (tool==='find_appointment') {
    const refs = args.booking_references
    // A supplied reference always takes precedence; name lookup is an operator opt-in.
    if (refs === undefined || (Array.isArray(refs) && refs.length === 0)) {
      const name = typeof args.customer_name === 'string' ? args.customer_name.trim() : ''
      if (name.length < 2 || name.length > 160) return failed('reference_required')
      const {data,error} = await db.rpc('recepta_find_appointments_by_name',{
        p_client:context.clientId,p_agent:context.agentId,p_call:context.callId,p_phone:phone,p_name:name,
      })
      if (error) throw error
      const result = objectValue(data)
      if (result.success!==true || !Array.isArray(result.appointments) || result.appointments.length<1 || result.appointments.length>5) {
        return { ...failed('reference_required'),instruction:'Ask for the original booking reference. Do not disclose whether an appointment exists.' }
      }
      return {success:true,appointments:result.appointments.map(record=>verified(objectValue(record))),
        instruction:'Read only the verified appointment times and timezone. Never speak or ask for the session token. If multiple appointments were verified, ask the caller to select one.'}
    }
    if (!Array.isArray(refs) || refs.length<1 || refs.length>5 || !refs.every(ref => bookingReference(ref) !== null)) return failed()
    const records = new Map<string, ReturnType<typeof verified>>()
    for (const ref of new Set(refs.map(bookingReference))) {
      if (ref === null) return failed()
      const record = await invoke(ref,'find')
      if (record.success!==true) return failed(record.reason==='service_unavailable' ? 'service_unavailable' : 'verification_failed')
      const appointment = verified(record)
      records.set(appointment.appointment_id, appointment)
    }
    return {success:true,appointments:[...records.values()],instruction:'Read only the verified appointment times and timezone. Never speak or ask the caller for the session token. If multiple appointments were verified, ask the caller to select one.'}
  }
  if (!uuid(args.appointment_id)) return failed()
  const id = args.appointment_id.toLowerCase()
  const version = verifyAppointmentSession(context,id,args.verified_session_token)
  if (version===null) return failed()
  if (tool==='cancel_appointment' && (args.confirmed!==true || !heardCancellationConfirmation(call))) return failed('confirmation_required')
  if (tool==='reschedule_appointment' && (!validDate(args.new_date) || !validTime(args.new_time))) return failed('invalid_local_date_or_time')
  if (tool==='check_appointment_availability') {
    if (!validDate(args.requested_date)) {
      return { available:false, reason:'invalid_local_date_or_time', alternatives:[], instruction:'Ask for a valid business-local date; this is not a fully booked day.' }
    }
    const flexible = args.requested_time === undefined || args.requested_time === null || args.requested_time === ''
    if (!flexible) {
      if (!validTime(args.requested_time)) return { available:false, reason:'invalid_local_date_or_time', alternatives:[], instruction:'Ask for a valid time; this is not a fully booked day.' }
      return invoke(id,'check',version)
    }
    // The existing versioned RPC checks capacity, store hours, duration and buffer.
    // Starting at midnight invokes its forward alternative search (up to seven days).
    // If midnight itself is bookable, advance the cursor to gather more options.
    const choices = new Set<string>()
    let timeZone: unknown
    let originalStart: unknown
    for (let minute=0; minute<4 && choices.size<3; minute++) {
      const result = await invoke(id,'check',version,'00:'+String(minute).padStart(2,'0'))
      if (['verification_failed','service_unavailable','appointment_changed','appointment_not_eligible','automatic_booking_disabled','outside_booking_horizon','invalid_local_date_or_time','pro_required','schedule_not_set'].includes(String(result.reason))) {
        return {...result, alternatives:[], instruction:'Do not describe this as a fully booked day. Explain the scheduling or verification issue; the original appointment has not been changed.'}
      }
      timeZone = result.time_zone ?? timeZone
      if (result.available===true && typeof result.start==='string') {
        // Exact-slot checks allow the original slot; flexible suggestions must exclude it.
        if (originalStart===undefined) {
          const current=await invoke(id,'find')
          if (current.success!==true || current.booking_version!==version || typeof current.start!=='string') return failed('appointment_changed')
          originalStart=current.start
        }
        if (Date.parse(result.start)!==Date.parse(String(originalStart))) choices.add(result.start)
      } else if (result.available===false && Array.isArray(result.alternatives)) {
        for (const start of result.alternatives) {
          if (typeof start==='string' && choices.size<3) choices.add(start)
        }
        break
      } else {
        return {available:false,reason:'availability_unverified',alternatives:[],instruction:'The calendar could not be verified. Do not say the day is fully booked.'}
      }
    }
    return {available:choices.size>0,reason:choices.size>0?'choose_a_time':'no_slots_in_search_window',
      alternatives:[...choices],time_zone:timeZone,
      instruction:choices.size>0?'Offer the returned dates and times, including later days if needed. These are not reservations. Confirm the selected time before moving the original appointment.':'No available alternatives were returned in the bounded search. Offer to check a later date; the original appointment is unchanged.'}
  }
  const action = tool==='cancel_appointment' ? 'cancel' : 'reschedule'
  const record = await invoke(id,action,version)
  if (record.success!==true) {
    if (record.reason==='verification_failed' || record.reason==='service_unavailable') return failed(String(record.reason))
    return {success:false,reason:record.reason,alternatives:record.alternatives ?? [],time_zone:record.time_zone,
      instruction:'This request did not change the appointment. Offer only returned alternatives; otherwise ask the caller to contact the business. If the appointment changed, verify again.'}
  }
  if (action==='cancel') {
    if (record.status!=='cancelled') throw new Error('Cancellation not confirmed.')
    return {success:true,status:'cancelled',appointment_id:id,already_applied:record.already_applied===true,
      instruction:'Confirm cancellation. Do not claim an email was delivered.'}
  }
  if (record.status!=='booked' || typeof record.start!=='string') throw new Error('Reschedule not confirmed.')
  return {success:true,...verified(record),already_applied:record.already_applied===true,
    instruction:'Confirm the updated time and timezone. Do not claim an email was delivered.'}
}
